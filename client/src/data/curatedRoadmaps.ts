export function normalizeTrackName(track?: string): string {
  if (!track) return "App Development";
  const lower = track.toLowerCase().trim();
  if (lower.includes("app") || lower.includes("mobile") || lower.includes("react native") || lower.includes("flutter")) {
    return "App Development";
  }
  if (lower.includes("web") || lower.includes("frontend") || lower.includes("full") || lower.includes("backend")) {
    return "Web Development";
  }
  if (lower.includes("ai") || lower.includes("ml") || lower.includes("machine") || lower.includes("learning")) {
    return "AI / ML";
  }
  if (lower.includes("cyber") || lower.includes("security") || lower.includes("penetration") || lower.includes("ethical")) {
    return "Cybersecurity";
  }
  if (lower.includes("data") || lower.includes("analytics") || lower.includes("sql") || lower.includes("bi")) {
    return "Data / Analytics";
  }
  return "App Development";
}

export function getCuratedRoadmap(trackName?: string): Roadmap {
  const normalized = normalizeTrackName(trackName);
  return CURATED_ROADMAPS[normalized] || CURATED_ROADMAPS["App Development"];
}
